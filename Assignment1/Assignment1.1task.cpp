#include <iostream>
#include <cstdlib>   // для rand(), srand()
#include <ctime>     // для time()

using namespace std;

int main() {
    // На основе Лекция №1: работа с большими массивами данных — основа параллельного программирования.
    // Здесь демонстрируем динамическое выделение памяти для массива произвольного размера.
    const int SIZE = 50000;  // Размер массива — 50 000 элементов

    // Динамическое выделение памяти в куче (heap)
    // Статический массив не подошёл бы для больших или неизвестных заранее размеров.
    int* arr = new int[SIZE];

    // Инициализация генератора случайных чисел
    srand(static_cast<unsigned>(time(nullptr)));

    double sum = 0.0;  // Накопительная сумма для вычисления среднего
    for (int i = 0; i < SIZE; ++i) {
        arr[i] = rand() % 100 + 1;  // Случайные числа от 1 до 100
        sum += arr[i];
    }

    // Вычисление среднего арифметического
    double average = sum / SIZE;

    // Вывод только на английском — избежание проблем с кириллицей в консоли Windows
    cout << "Average value of array elements: " << average << endl;

    // Обязательное освобождение динамически выделенной памяти
    // Иначе — утечка памяти (memory leak)
    delete[] arr;

    return 0;
}