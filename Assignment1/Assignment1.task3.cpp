#include <iostream>
#include <chrono>    // Для высокоточного замера времени выполнения
#include <cstdlib>   // Для rand() и srand()
#include <ctime>     // Для time()
#include <omp.h>     // Заголовок библиотеки OpenMP — ключевой инструмент многопоточности на CPU (Лекция №2)

using namespace std;

int main() {
    // Лекция №1: Параллельное программирование необходимо для ускорения обработки больших объёмов данных.
    // Пример из лекции (стр. 15–16): параллельное суммирование массива на 4 потока даёт ускорение почти в 4 раза.
    // Здесь мы применяем аналогичный подход к поиску минимума и максимума в массиве из 1 000 000 элементов.
    // Лекция №2 (Часть 1): Современные CPU — многоядерные, что позволяет одновременно выполнять несколько потоков.
    const int SIZE = 1000000;  // Размер массива — типичный объём для демонстрации выгоды параллелизма

    // Динамическое выделение памяти под большой массив (в куче — heap)
    // Лекция №1 подразумевает работу с большими данными, для которых статические массивы не подходят.
    int* arr = new int[SIZE];

    // Инициализация генератора случайных чисел один раз — хорошая практика
    srand(static_cast<unsigned>(time(nullptr)));

    // Заполнение массива случайными значениями от 0 до 999999
    // Это имитирует реальные данные, над которыми нужно выполнять вычисления.
    for (int i = 0; i < SIZE; ++i) {
        arr[i] = rand() % 1000000;
    }

    // === Последовательная версия алгоритма (для сравнения производительности) ===
    // Лекция №1 (стр. 9–11): Последовательное программирование выполняет операции одну за другой,
    // что медленно на больших данных. Это базовый подход без параллелизма.
    auto start_seq = chrono::high_resolution_clock::now();

    int min_seq = arr[0];  // Начальное значение минимума
    int max_seq = arr[0];  // Начальное значение максимума

    for (int i = 1; i < SIZE; ++i) {
        if (arr[i] < min_seq) min_seq = arr[i];  // Обновление минимума
        if (arr[i] > max_seq) max_seq = arr[i];  // Обновление максимума
    }

    auto end_seq = chrono::high_resolution_clock::now();
    chrono::duration<double, milli> dur_seq = end_seq - start_seq;
    // Время выполнения последовательной версии будет служить эталоном для расчёта ускорения.

    // === Параллельная версия с использованием OpenMP ===
    // Лекция №2 (Часть 3): OpenMP — это библиотека для простого добавления многопоточности на CPU.
    // Директива #pragma omp parallel for автоматически создаёт потоки и распределяет итерации цикла между ядрами CPU.
    // Лекция №2 (стр. 20): Механизм reduction необходим для безопасных операций над общей переменной в параллельных потоках.
    // Без reduction несколько потоков одновременно обращались бы к min_par/max_par → race condition (состояние гонки).
    // reduction(min:...) и reduction(max:...) создают локальные копии переменных для каждого потока,
    // а в конце объединяют результаты правильным образом.
    int min_par = arr[0];
    int max_par = arr[0];

    auto start_par = chrono::high_resolution_clock::now();

#pragma omp parallel for reduction(min:min_par) reduction(max:max_par)
    for (int i = 0; i < SIZE; ++i) {
        if (arr[i] < min_par) min_par = arr[i];
        if (arr[i] > max_par) max_par = arr[i];
    }

    auto end_par = chrono::high_resolution_clock::now();
    chrono::duration<double, milli> dur_par = end_par - start_par;

    // === Вывод результатов на английском (чтобы избежать проблем с кодировкой в консоли Windows) ===
    cout << "Sequential version:" << endl;
    cout << "  Min = " << min_seq << ", Max = " << max_seq
        << ", Time: " << dur_seq.count() << " ms" << endl;

    cout << "Parallel version (OpenMP):" << endl;
    cout << "  Min = " << min_par << ", Max = " << max_par
        << ", Time: " << dur_par.count() << " ms" << endl;

    // Расчёт ускорения (speedup) — ключевой показатель эффективности параллелизации (Лекция №1)
    // Чем больше ядер CPU и чем лучше распараллелена задача — тем выше коэффициент.
    // На практике ускорение ограничено законом Амдала и накладными расходами OpenMP.
    double speedup = dur_seq.count() / dur_par.count();
    cout << "Speedup: approximately " << speedup
        << "x (depends on number of CPU cores and architecture)" << endl;

    // Обязательное освобождение динамически выделенной памяти
    // Лекция №1 подразумевает работу с большими данными → важно избегать утечек памяти.
    delete[] arr;

    return 0;
}