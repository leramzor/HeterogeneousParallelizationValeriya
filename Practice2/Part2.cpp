#include <iostream>      // Подключаем библиотеку для ввода-вывода: cout, endl и т.д.
#include <vector>        // Подключаем контейнер vector — динамический массив с автоматическим управлением памятью
#include <random>        // Подключаем библиотеку для генерации случайных чисел (mt19937 и распределения)
#include <chrono>        // Подключаем библиотеку для точного измерения времени выполнения алгоритмов
#include <omp.h>         // Подключаем заголовочный файл OpenMP для использования параллельных директив

using namespace std;     // Используем пространство имён std, чтобы не писать std:: перед всеми объектами

// Функция для заполнения вектора случайными числами (общая для всех частей)
void fill_array(vector<int>& arr) {  // Принимаем вектор по ссылке, чтобы не копировать данные
    mt19937 gen(static_cast<unsigned>(time(nullptr)));  // Создаём генератор Mersenne Twister и инициализируем его текущим временем
    uniform_int_distribution<int> dist(1, 100000);     // Задаём равномерное распределение: целые числа от 1 до 100000
    for (size_t i = 0; i < arr.size(); ++i) {          // Цикл по всем элементам вектора
        arr[i] = dist(gen);                            // Присваиваем i-му элементу случайное значение из распределения
    }                                                  // Большие случайные числа дают худший случай O(n²) — как требуется в практике №2
}                                                      // Конец функции fill_array

// Последовательная реализация сортировки выбором
void selection_sort_seq(vector<int>& arr) {             // Функция принимает вектор по ссылке для изменения на месте
    size_t n = arr.size();                             // Сохраняем размер массива в переменную n для удобства и скорости
    for (size_t i = 0; i < n - 1; ++i) {                // Внешний цикл: проходим от 0 до предпоследнего элемента
        size_t min_idx = i;                            // Изначально считаем, что минимальный элемент находится на позиции i
        for (size_t j = i + 1; j < n; ++j) {           // Внутренний цикл: ищем минимум в неотсортированной части (от i+1 до конца)
            if (arr[j] < arr[min_idx]) {               // Если найден элемент меньше текущего минимума
                min_idx = j;                           // Обновляем индекс минимума
            }                                          // Конец условия сравнения
        }                                              // Конец внутреннего цикла поиска минимума
        if (min_idx != i) {                            // Если минимум не на своей позиции (нужен обмен)
            swap(arr[i], arr[min_idx]);                // Меняем местами элемент на позиции i и найденный минимум
        }                                              // Конец проверки на необходимость обмена
    }                                                  // Конец внешнего цикла — массив полностью отсортирован
}                                                      // Конец функции selection_sort_seq

// Параллельная реализация сортировки выбором с параллельным поиском минимума
void selection_sort_par(vector<int>& arr) {             // Функция принимает вектор по ссылке
    size_t n = arr.size();                             // Получаем размер массива
    for (size_t i = 0; i < n - 1; ++i) {                // Внешний цикл остаётся последовательным (обмен только один раз)
        size_t min_idx = i;                            // Изначально предполагаем минимум на позиции i
        // Директива OpenMP: параллелим внутренний цикл поиска минимума
        // reduction(min:min_idx) — каждый поток ищет свой локальный минимум, в конце выбирается глобальный
#pragma omp parallel for reduction(min:min_idx)
        for (int j = static_cast<int>(i + 1); j < static_cast<int>(n); ++j) {  // Цикл по неотсортированной части
            if (arr[j] < arr[min_idx]) {               // Сравниваем текущий элемент с текущим минимумом потока
                min_idx = static_cast<size_t>(j);      // Обновляем локальный индекс минимума (без race condition благодаря reduction)
            }                                          // Конец условия
        }                                              // Конец параллельного цикла
        if (min_idx != i) {                            // После завершения всех потоков проверяем, нужен ли обмен
            swap(arr[i], arr[min_idx]);                // Выполняем обмен последовательно
        }                                              // Конец проверки
    }                                                  // Конец внешнего цикла
}                                                      // Конец функции — массив отсортирован

int main() {                                           // Точка входа в программу
    const size_t N = 15000;                            // Константа: размер массива — 15 тысяч элементов (компромисс между временем и эффектом параллелизации)
    vector<int> arr_seq(N);                            // Создаём вектор для последовательной версии
    vector<int> arr_par(N);                            // Создаём вектор для параллельной версии

    fill_array(arr_seq);                               // Заполняем последовательный массив случайными данными
    arr_par = arr_seq;                                 // Копируем те же данные в параллельный массив — для честного сравнения

    auto start_seq = chrono::high_resolution_clock::now();  // Запоминаем время начала последовательной сортировки
    selection_sort_seq(arr_seq);                       // Выполняем последовательную сортировку
    auto end_seq = chrono::high_resolution_clock::now();    // Запоминаем время окончания последовательной версии
    chrono::duration<double> seq_time = end_seq - start_seq; // Вычисляем длительность в секундах (double)

    auto start_par = chrono::high_resolution_clock::now();  // Запоминаем время начала параллельной сортировки
    selection_sort_par(arr_par);                       // Выполняем параллельную сортировку
    auto end_par = chrono::high_resolution_clock::now();    // Запоминаем время окончания параллельной версии
    chrono::duration<double> par_time = end_par - start_par; // Вычисляем длительность параллельной версии

    cout << "Part 2: Selection Sort\n";                // Выводим заголовок части на английском
    cout << "Array size: " << N << " elements\n";      // Выводим размер массива
    cout << "Sequential version time: " << seq_time.count() << " seconds\n";  // Время последовательной версии
    cout << "Parallel version time:   " << par_time.count() << " seconds\n";  // Время параллельной версии
    cout << "Speedup achieved: " << seq_time.count() / par_time.count() << "x\n";  // Вычисляем и выводим ускорение
    cout << "Note: Parallel minimum search using OpenMP reduction(min:) — effective on multi-core CPU\n";  // Пояснение подхода

    return 0;                                          // Возвращаем 0 — успешное завершение программы
}                                                      // Конец main