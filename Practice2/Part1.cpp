#include <iostream>      // Библиотека для стандартного ввода-вывода: используется для cout и endl
#include <vector>        // Динамический контейнер std::vector — автоматически управляет памятью, удобен для массивов переменного размера
#include <random>        // Библиотека для генерации случайных чисел: mt19937 и uniform_int_distribution — современный и качественный подход
#include <chrono>        // Библиотека для высокоточного измерения времени: chrono::high_resolution_clock — точнее, чем time()
#include <omp.h>         // Заголовочный файл OpenMP: необходим для использования директив #pragma omp

using namespace std;     // Позволяет использовать имена из std без префикса std:: (cout, vector, chrono и т.д.)

// Функция заполнения массива случайными целыми числами
void fill_array(vector<int>& arr) {
    // Создаём генератор случайных чисел Mersenne Twister — один из лучших псевдослучайных генераторов
    mt19937 gen(static_cast<unsigned>(time(nullptr)));  // Инициализируем seed текущим временем
    // Задаём равномерное распределение: числа от 1 до 100000 включительно
    uniform_int_distribution<int> dist(1, 100000);
    // Проходим по всем элементам вектора
    for (size_t i = 0; i < arr.size(); ++i) {
        // Присваиваем каждому элементу случайное значение из заданного диапазона
        arr[i] = dist(gen);
    }
    // Согласно практике №2: большие случайные числа обеспечивают худший случай для сортировки O(n²)
}

// Последовательная реализация классической сортировки пузырьком
void bubble_sort_seq(vector<int>& arr) {
    size_t n = arr.size();                             // Сохраняем размер массива для удобства и читаемости
    // Внешний цикл: выполняем n-1 проходов по массиву
    for (size_t i = 0; i < n - 1; ++i) {
        // Внутренний цикл: сравниваем соседние элементы до позиции n-i-1 (после каждого прохода последние элементы уже на месте)
        for (size_t j = 0; j < n - i - 1; ++j) {
            // Если левый элемент больше правого — нарушен порядок
            if (arr[j] > arr[j + 1]) {
                // Меняем элементы местами с помощью стандартной функции swap
                swap(arr[j], arr[j + 1]);
            }
        }
    }
    // После завершения алгоритм гарантирует полную отсортированность по возрастанию
    // Сложность: O(n²) сравнений и обменов — как указано в теоретической части практики №2
}

// Параллельная реализация сортировки пузырьком методом чётных/нечётных фаз (Odd-Even Transposition Sort)
void bubble_sort_par(vector<int>& arr) {
    size_t n = arr.size();                             // Размер массива
    bool swapped = true;                               // Флаг оптимизации: если на проходе не было обменов — массив уже отсортирован
    size_t phase = 0;                                  // Счётчик текущей фазы (прохода)

    // Основной цикл продолжается, пока происходят обмены и не достигнут конец массива
    while (swapped && phase < n - 1) {
        swapped = false;                               // Сбрасываем флаг перед началом новой фазы

        // === Чётная фаза ===
        // Сравниваем и обмениваем пары элементов с чётными индексами: (0,1), (2,3), (4,5), ...
        // Эти операции полностью независимы — идеально для параллельного выполнения
        // Согласно Лекции №2: многоядерный CPU может одновременно выполнять независимые задачи на разных ядрах
#pragma omp parallel for
        for (int j = 0; j < static_cast<int>(n - 1 - phase); j += 2) {
            // Сравниваем пару элементов
            if (arr[j] > arr[j + 1]) {
                swap(arr[j], arr[j + 1]);              // Обмен, если порядок нарушен
                swapped = true;                        // Устанавливаем флаг — был хотя бы один обмен
            }
        }

        // === Нечётная фаза ===
        // Сравниваем пары с нечётными индексами: (1,2), (3,4), (5,6), ...
        // Также независимые операции — снова параллелим
#pragma omp parallel for
        for (int j = 1; j < static_cast<int>(n - 1 - phase); j += 2) {
            if (arr[j] > arr[j + 1]) {
                swap(arr[j], arr[j + 1]);
                swapped = true;
            }
        }

        ++phase;                                       // Переходим к следующей фазе
    }
    // Этот подход описан в практике №2 как один из способов параллелизации пузырьковой сортировки
}

int main() {
    const size_t N = 20000;                            // Размер массива — 20 тысяч элементов: достаточно большой для замера ускорения, но не слишком долгий
    vector<int> arr_seq(N);                            // Вектор для последовательной версии сортировки
    vector<int> arr_par(N);                            // Вектор для параллельной версии (отдельная копия для честного сравнения)

    fill_array(arr_seq);                               // Заполняем первый массив случайными данными
    arr_par = arr_seq;                                 // Копируем те же данные во второй массив — идентичные входные условия

    // === Измерение времени последовательной версии ===
    auto start_seq = chrono::high_resolution_clock::now();  // Запоминаем точное время начала выполнения
    bubble_sort_seq(arr_seq);                          // Запускаем последовательную сортировку
    auto end_seq = chrono::high_resolution_clock::now();    // Запоминаем время окончания
    chrono::duration<double> seq_time = end_seq - start_seq; // Вычисляем длительность в секундах

    // === Измерение времени параллельной версии ===
    auto start_par = chrono::high_resolution_clock::now();
    bubble_sort_par(arr_par);
    auto end_par = chrono::high_resolution_clock::now();
    chrono::duration<double> par_time = end_par - start_par;

    // === Вывод результатов на английском языке ===
    cout << "Part 1: Bubble Sort (Odd-Even Parallel Version)\n";
    cout << "Array size: " << N << " elements\n";
    cout << "Sequential version time: " << seq_time.count() << " seconds\n";
    cout << "Parallel version time:   " << par_time.count() << " seconds\n";
    cout << "Speedup achieved: " << seq_time.count() / par_time.count() << "x\n";
    cout << "Note: Parallelization uses independent even/odd phases, suitable for multi-core CPU (Lecture #2)\n";

    return 0;                                          // Успешное завершение программы
}